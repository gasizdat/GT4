namespace GT4.UI.DeviceTests;

public class ImageDataConverterTests
{
  private const int CacheSizeLimit = 1024 * 1024;
  private const int MaxSize = 8;

  // A minimal valid 40x20 PNG: the downsizing branch really decodes and re-encodes these bytes, so
  // arbitrary ones would throw rather than resize.
  private static readonly byte[] SamplePng =
  [
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00, 0x14, 0x08, 0x06, 0x00, 0x00, 0x00, 0xFF, 0x46, 0x7F,
    0xBB, 0x00, 0x00, 0x00, 0x01, 0x73, 0x52, 0x47, 0x42, 0x00, 0xAE, 0xCE, 0x1C, 0xE9, 0x00, 0x00,
    0x00, 0x04, 0x67, 0x41, 0x4D, 0x41, 0x00, 0x00, 0xB1, 0x8F, 0x0B, 0xFC, 0x61, 0x05, 0x00, 0x00,
    0x00, 0x09, 0x70, 0x48, 0x59, 0x73, 0x00, 0x00, 0x0E, 0xC3, 0x00, 0x00, 0x0E, 0xC3, 0x01, 0xC7,
    0x6F, 0xA8, 0x64, 0x00, 0x00, 0x00, 0x35, 0x49, 0x44, 0x41, 0x54, 0x48, 0x4B, 0xED, 0xCE, 0xA1,
    0x01, 0x00, 0x00, 0x08, 0x80, 0x30, 0x8F, 0xF5, 0x25, 0xCF, 0xF4, 0x06, 0xED, 0x56, 0x8A, 0x81,
    0xB0, 0x42, 0x22, 0xB2, 0x7A, 0x3E, 0x8B, 0x1B, 0xBE, 0x71, 0x90, 0x72, 0x90, 0x72, 0x90, 0x72,
    0x90, 0x72, 0x90, 0x72, 0x90, 0x72, 0x90, 0x72, 0x90, 0x72, 0x90, 0x5A, 0x1E, 0x11, 0x0C, 0x28,
    0xBD, 0x49, 0x70, 0x61, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
  ];

  private static ImageDataConverter Converter() =>
    new(Mock.Of<IHttpClientFactory>(), new ImageCache(CacheSizeLimit));

  private static async Task<PhotoInfo> ConvertedAsync(Data data)
  {
    var converted = await Converter().ToObjectAsync(data, CancellationToken.None);
    return Assert.IsType<PhotoInfo>(converted);
  }

  // Read here, off bytes the converter is holding anyway, so nothing downstream has to copy an image
  // back out of its ImageSource to learn how big it is.
  [Fact]
  public async Task ToObjectAsync_Image_CarriesThePixelSizeOfItsBytes()
  {
    var data = new Data(1, SamplePng, "image/png", DataCategory.PersonMainPhoto);

    var photo = await ConvertedAsync(data);

    Assert.Equal(new Size(40, 20), photo.PixelSize);
  }

  // What renders here is a resize, so reporting the stored dimensions would lay the image out at a size
  // it isn't drawn at.
  [Fact]
  public async Task ToObjectAsync_DownsizedImage_CarriesNoPixelSize()
  {
    var data = new Data(2, SamplePng, "image/png", DataCategory.PersonMainPhoto);
    var thumbnail = new ImageDataWithMaxSize(data, MaxSize);

    var photo = await ConvertedAsync(thumbnail);

    Assert.Null(photo.PixelSize);
  }
}
